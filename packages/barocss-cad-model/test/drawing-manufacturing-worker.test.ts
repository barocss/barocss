import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { Worker } from 'node:worker_threads';
import { once } from 'node:events';
import { WireSender } from '../src/engine/wireDoc';
import { drawingDocument } from '../src/drawing/scope';
import { readDrawing, sectionsOf } from '../src/drawing/types';
import type { DrawingResult } from '../src/drawing/project';
import { drawingInputs, runDrawingTool } from '../src/chat/drawing';
import { manufacturingDocument, manufacturingOptions } from './fixtures/drawing-manufacturing';

test('A9-4 production worker consumes scoped manufacturing sections from actual set result', { timeout: 30000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'drawing-manufacturing-worker-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const { build } = createRequire(resolve(import.meta.dirname, '../../../package.json'))('esbuild') as typeof import('esbuild');
  await build({ entryPoints: [resolve(import.meta.dirname, '../../../apps/cad-studio/src/engine/engine.worker.ts')], outfile: join(dir, 'production.mjs'), bundle: true, platform: 'node', format: 'esm', target: 'node22', logLevel: 'warning' });
  await writeFile(join(dir, 'adapter.mjs'), `import {parentPort} from 'node:worker_threads';
globalThis.self={postMessage:(v,transfer)=>parentPort.postMessage(v,transfer)};
await import('./production.mjs');
parentPort.on('message',data=>self.onmessage({data}));parentPort.postMessage({ready:true});`);
  const worker = new Worker(join(dir, 'adapter.mjs')); t.after(() => worker.terminate());
  const [ready] = await once(worker, 'message'); assert.deepEqual(ready, { ready: true });
  const doc = manufacturingDocument(), set = runDrawingTool(doc, 'set_drawing', manufacturingOptions);
  assert.ok(!('error' in set));
  const native = drawingInputs(set.doc); assert.ok(typeof native !== 'string', String(native));
  const settings = readDrawing(set.doc.drawing), packed = new WireSender().pack(drawingDocument(set.doc, settings));
  const response = once(worker, 'message');
  worker.postMessage({ type: 'drawing', id: 1, doc: packed, options: { sections: sectionsOf(settings) } });
  const [reply] = await response as [{ id: number; drawing: DrawingResult }];
  assert.equal(reply.id, 1); assert.ok(reply.drawing.ok, JSON.stringify(reply.drawing));
  assert.deepEqual(reply.drawing.views, native.views);
  assert.equal(reply.drawing.sections?.length, 2);
  assert.ok(reply.drawing.sections?.every(c => c.result.ok));
  assert.deepEqual(set.doc.frames, doc.frames, 'drawing options do not change authored welds');
});
