// The Tools page's action tables, generated from the tool contract's groups (cad-model chat/groups.ts, GROUPS): each
// tool, what it is for, and each action with the handler it stands for and its arguments. Writes docs/agent/_tools.md,
// which agent/tools.md includes. `--check` writes nothing and exits 1 when the file differs from the code.
//   node scripts/agent-tools.mjs [--check]
// (Node 22 strips groups.ts's types itself; the file imports nothing.)
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const docs = resolve(import.meta.dirname, '..');
const source = resolve(docs, '../../packages/barocss-cad-model/src/chat/groups.ts');
const target = join(docs, 'docs/agent/_tools.md');
const { GROUPS, V2_ALIASES } = await import(pathToFileURL(source).href);

/** A hint as a reader reads it: the roadmap's step codes in brackets ("(FRb)", "(D155)") left out, pipes escaped. */
const STEP_CODE = /\s*\((?:[A-Z]{1,3}[a-z0-9.]*\d[a-z0-9.]*|FR[a-z]\d?)\)/g;
const cell = text => text.replace(STEP_CODE, '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const lines = ['<!-- Generated by scripts/agent-tools.mjs from cad-model chat/groups.ts. Do not edit by hand. -->', ''];
for (const [name, group] of Object.entries(GROUPS)) {
  if (name === 'describe') continue;
  lines.push(`### \`${name}\`: ${group.title}`, '', ...(group.about ? [group.about, ''] : []));
  lines.push('| Action | Handler | Arguments and notes |', '|---|---|---|');
  for (const [action, [handler, hint]] of Object.entries(group.actions)) {
    const alias = V2_ALIASES.has(`${name}.${action}`) ? ' (an alias, kept for agents that know it)' : '';
    lines.push(`| \`${name}.${action}\` | \`${handler}\` | ${hint ? cell(hint) : '—'}${alias} |`);
  }
  lines.push('');
}
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(target, 'utf8'); } catch { /* not written yet */ }
  if (now !== text) { console.error('docs/agent/_tools.md differs from chat/groups.ts: run node scripts/agent-tools.mjs'); process.exit(1); }
} else writeFileSync(target, text);
