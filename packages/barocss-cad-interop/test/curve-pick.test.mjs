import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { evaluateCurve } from '@barocss/cad';
import { Line, Mesh, Raycaster, Vector3 as ThreeVector3 } from 'three';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { Mesh as BabylonMesh } from '@babylonjs/core/Meshes/mesh.js';
import { Ray } from '@babylonjs/core/Culling/ray.js';
import { Vector3 as BabylonVector3 } from '@babylonjs/core/Maths/math.vector.js';
import { BaroCADLoader, resolveBaroCadThreeCurvePick } from '@barocss/cad-interop/three';
import { BaroCADBabylonLoader, resolveBaroCadBabylonCurvePick } from '@barocss/cad-interop/babylon';

const source = readFileSync(new URL('../examples/curve-display.barocad', import.meta.url), 'utf8');
const options = { sourceVersion: 0, countU: 8, countV: 8, unitsPerMillimeter: 0.001,
  curveDisplay: { chordToleranceMM: 0.1, maxSegments: 128, maxDepth: 16 } };
const near = (actual, expected, tolerance = 1e-7) => assert.ok(Math.abs(actual - expected) <= tolerance, `${actual} vs ${expected}`);

const three = new BaroCADLoader(options).parse(source);
assert.equal(three.source, source);
const threeLine = three.group.children.find(child => child instanceof Line && child.name === 'asymmetric_nonunit');
assert.ok(threeLine);
threeLine.name = 'mutable-display-name';
threeLine.userData.barocss.curveId = 'mutable-metadata';
threeLine.position.set(0.18, 0.07, -0.03);
threeLine.rotation.z = 0.2;
threeLine.scale.set(1.3, 0.8, 1.1);
three.group.updateMatrixWorld(true);
const threeCurve = three.curves.find(curve => curve.curveId === 'asymmetric_nonunit');
const threeSegment = Math.floor(threeCurve.sample.segments.length / 2);
const threeStart = new ThreeVector3().fromArray(threeCurve.positions, threeSegment * 3);
const threeEnd = new ThreeVector3().fromArray(threeCurve.positions, (threeSegment + 1) * 3);
const threeTarget = threeStart.clone().lerp(threeEnd, 0.5).applyMatrix4(threeLine.matrixWorld);
const raycaster = new Raycaster(threeTarget.clone().add(new ThreeVector3(0, 0, 1)), new ThreeVector3(0, 0, -1), 0, 3);
raycaster.params.Line.threshold = 0.002;
const threeHit = raycaster.intersectObject(threeLine)[0];
assert.ok(threeHit, 'Three Raycaster must hit the real transformed Curve line');
const threePick = resolveBaroCadThreeCurvePick(three, threeHit);
assert.equal(threePick.target, 'three');
assert.equal(threePick.curveId, 'asymmetric_nonunit');
assert.equal(threePick.modelName, 'curve_display_demo');
assert.deepEqual(threePick.interval, [threeCurve.sample.parameters[threePick.segmentIndex], threeCurve.sample.parameters[threePick.segmentIndex + 1]]);
assert.ok(threePick.parameterApprox >= -1 && threePick.parameterApprox <= 2);
assert.ok(threePick.fraction >= 0 && threePick.fraction <= 1);
for (const [index, value] of evaluateCurve(three.model.objects[1], threePick.parameterApprox).entries()) near(threePick.nativePointMM[index], value);
for (let index = 0; index < 3; index++) near(threePick.worldPoint[index], threeHit.point.getComponent(index), 1e-5);
const threeNative = [...threePick.nativePointMM];
three.model.objects[1].controlPoints[0][0] += 1000;
assert.deepEqual(resolveBaroCadThreeCurvePick(three, threeHit).nativePointMM, threeNative);
const threeSurface = three.group.children.find(child => child instanceof Mesh);
assert.equal(resolveBaroCadThreeCurvePick(three, { object: threeSurface }), null);
assert.equal(resolveBaroCadThreeCurvePick(three, null), null);
assert.throws(() => resolveBaroCadThreeCurvePick(three, { object: new Line() }), /foreign/);
const getterHit = {};
Object.defineProperty(getterHit, 'object', { get() { throw new Error('must not read getter'); } });
assert.throws(() => resolveBaroCadThreeCurvePick(three, getterHit), /own data/);
const oldPosition = threeLine.geometry.getAttribute('position').array[0];
threeLine.geometry.getAttribute('position').array[0] += 1;
assert.throws(() => resolveBaroCadThreeCurvePick(three, threeHit), /stale/);
threeLine.geometry.getAttribute('position').array[0] = oldPosition;
assert.throws(() => resolveBaroCadThreeCurvePick(three, { ...threeHit, index: 999999 }), /index/);
assert.throws(() => resolveBaroCadThreeCurvePick({ ...three }, threeHit), /result from this loader/);
threeLine.scale.x = 0;
assert.throws(() => resolveBaroCadThreeCurvePick(three, threeHit), /invertible/);
threeLine.scale.x = 1.3;
three.dispose();
assert.throws(() => resolveBaroCadThreeCurvePick(three, threeHit), /disposed/);

const engine = new NullEngine();
const scene = new Scene(engine);
scene.useRightHandedSystem = true;
const caller = new BabylonMesh('caller', scene);
try {
  const babylon = new BaroCADBabylonLoader(scene, options).parse(source);
  assert.equal(babylon.source, source);
  const line = babylon.meshes.find(mesh => mesh.metadata?.barocss?.curveId === 'asymmetric_nonunit');
  assert.ok(line);
  line.name = 'mutable-display-name';
  line.metadata.barocss.curveId = 'mutable-metadata';
  line.position.set(0.18, 0.07, -0.03);
  line.rotation.z = 0.2;
  line.scaling.set(1.3, 0.8, 1.1);
  line.intersectionThreshold = 0.005;
  line.computeWorldMatrix(true);
  const curve = babylon.curves.find(item => item.curveId === 'asymmetric_nonunit');
  const segment = Math.floor(curve.sample.segments.length / 2);
  const start = BabylonVector3.FromArray(curve.positions, segment * 3);
  const end = BabylonVector3.FromArray(curve.positions, (segment + 1) * 3);
  const target = BabylonVector3.TransformCoordinates(BabylonVector3.Lerp(start, end, 0.5), line.getWorldMatrix());
  const ray = new Ray(target.add(new BabylonVector3(0, 0, 1)), new BabylonVector3(0, 0, -1), 3);
  const hit = ray.intersectsMesh(line);
  assert.ok(hit.hit, 'Babylon ray must hit the real transformed LinesMesh');
  const pick = resolveBaroCadBabylonCurvePick(babylon, hit);
  assert.equal(pick.target, 'babylon');
  assert.equal(pick.curveId, 'asymmetric_nonunit');
  assert.deepEqual(pick.interval, [curve.sample.parameters[pick.segmentIndex], curve.sample.parameters[pick.segmentIndex + 1]]);
  assert.ok(pick.parameterApprox >= -1 && pick.parameterApprox <= 2);
  for (const [index, value] of evaluateCurve(babylon.model.objects[1], pick.parameterApprox).entries()) near(pick.nativePointMM[index], value);
  const native = [...pick.nativePointMM];
  babylon.model.objects[1].controlPoints[0][0] += 1000;
  assert.deepEqual(resolveBaroCadBabylonCurvePick(babylon, hit).nativePointMM, native);
  const surface = babylon.meshes.find(mesh => mesh.metadata?.barocss?.surfaceId);
  assert.equal(resolveBaroCadBabylonCurvePick(babylon, { hit: true, pickedMesh: surface }), null);
  assert.equal(resolveBaroCadBabylonCurvePick(babylon, null), null);
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, { hit: true, pickedMesh: caller }), /foreign/);
  const originalIndices = [...line.getIndices()];
  line.setIndices([0, 1]);
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, hit), /stale/);
  line.setIndices(originalIndices);
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, { ...hit, faceId: 999999 }), /index/);
  const getterPick = { ...hit };
  Object.defineProperty(getterPick, 'faceId', { get() { throw new Error('must not read getter'); } });
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, getterPick), /own data/);
  line.scaling.x = 0;
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, hit), /invertible/);
  line.scaling.x = 1.3;
  babylon.dispose();
  assert.throws(() => resolveBaroCadBabylonCurvePick(babylon, hit), /disposed/);
  assert.equal(caller.isDisposed(), false);
  console.log(JSON.stringify({ result: 'curve-pick-ok', three: { index: threePick.segmentIndex, interval: threePick.interval, parameterApprox: threePick.parameterApprox },
    babylon: { index: pick.segmentIndex, interval: pick.interval, parameterApprox: pick.parameterApprox },
    sourceBytes: Buffer.byteLength(source), callerPreserved: !caller.isDisposed() }));
} finally {
  scene.dispose();
  engine.dispose();
}
