import assert from 'node:assert/strict';
import {copyPolygonMask,compilePolygonMask,insidePolygonMask,polygonMaskBounds} from '../../../dist/polygon-mask.js';
const identity=[1,0,0,1,0,0],view={panX:0,panY:0,zoom:1};
const polygon=(points)=>({commands:[{kind:'M',...points[0]},...points.slice(1).map(p=>({kind:'L',...p})),{kind:'Z'}]});
const l=polygon([{x:0,y:0},{x:100,y:0},{x:100,y:40},{x:40,y:40},{x:40,y:100},{x:0,y:100}]);
const copy=copyPolygonMask(l);assert.notEqual(copy.commands,l.commands);assert.notEqual(copy.commands[0],l.commands[0]);
const contour=compilePolygonMask(copy,identity,view,2);assert.equal(contour.length,12);
for(const point of[{x:10,y:90},{x:90,y:10},{x:40,y:70},{x:0,y:0}])assert.equal(insidePolygonMask(contour,point),true);
for(const point of[{x:70,y:70},{x:-1,y:10},{x:101,y:0}])assert.equal(insidePolygonMask(contour,point),false);
assert.deepEqual(polygonMaskBounds(contour),{x:0,y:0,width:100,height:100});
const reversed=polygon(l.commands.slice(0,-1).map(({x,y})=>({x,y})).reverse());
assert.equal(insidePolygonMask(compilePolygonMask(copyPolygonMask(reversed),identity,view,1),{x:10,y:90}),true);
const transformed=compilePolygonMask(copy,[-2,.4,.3,1.5,200,20],view,2);
const transform=p=>({x:-2*p.x+.3*p.y+200,y:.4*p.x+1.5*p.y+20});
assert.equal(insidePolygonMask(transformed,transform({x:10,y:90})),true);
assert.equal(insidePolygonMask(transformed,transform({x:70,y:70})),false);
const owned=[...contour];l.commands[0].x=200;assert.deepEqual([...contour],owned);assert.equal(copy.commands[0].x,0);
let refused=0;
const reject=(operation,code)=>{assert.throws(operation,e=>e?.code===code);refused++;};
reject(()=>copyPolygonMask(null),'INVALID_SCENE');
reject(()=>copyPolygonMask({commands:copy.commands,fill:[1,0,0,1]}),'INVALID_SCENE');
let getterCalls=0;const accessor={get commands(){getterCalls++;return copy.commands;}};
reject(()=>copyPolygonMask(accessor),'INVALID_SCENE');assert.equal(getterCalls,0);
reject(()=>copyPolygonMask(Object.assign(Object.create({}),{commands:copy.commands})),'INVALID_SCENE');
reject(()=>copyPolygonMask({commands:copy.commands.slice(0,-1)}),'INVALID_SCENE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:NaN,y:10},{x:10,y:10}])),'INVALID_SCENE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:1e6+1,y:10},{x:10,y:10}])),'INVALID_SCENE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:10,y:0},{x:10,y:0},{x:0,y:10}])),'INVALID_SCENE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:10,y:0},{x:20,y:0}])),'INVALID_SCENE');
reject(()=>copyPolygonMask({commands:[{kind:'M',x:0,y:0},{kind:'Q',cx:5,cy:10,x:10,y:0},{kind:'L',x:0,y:10},{kind:'Z'}]}),'UNSUPPORTED_FEATURE');
reject(()=>copyPolygonMask({commands:structuredClone([...copy.commands,...copy.commands]).map(c=>({...c}))}),'UNSUPPORTED_FEATURE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:20,y:20},{x:0,y:20},{x:20,y:0}])),'UNSUPPORTED_FEATURE');
reject(()=>copyPolygonMask(polygon([{x:0,y:0},{x:20,y:0},{x:10,y:0},{x:20,y:20},{x:0,y:20}])),'UNSUPPORTED_FEATURE');
const ring=n=>Array.from({length:n},(_,i)=>({x:100*Math.cos(i*2*Math.PI/n),y:100*Math.sin(i*2*Math.PI/n)}));
assert.equal(compilePolygonMask(copyPolygonMask(polygon(ring(32))),identity,view,2).length,64);
reject(()=>copyPolygonMask(polygon(ring(33))),'SCENE_LIMIT');
reject(()=>compilePolygonMask(copy,[1,0,0,1,1e9,0],view,2),'SCENE_LIMIT');
const tiny=copyPolygonMask(polygon([{x:0,y:0},{x:.001,y:0},{x:0,y:.001}]));
reject(()=>compilePolygonMask(tiny,[1,0,0,1,1e6,1e6],view,2),'SCENE_LIMIT');
