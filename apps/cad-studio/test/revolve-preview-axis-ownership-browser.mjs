import assert from 'node:assert/strict';
import { createFlow } from './flow-helper.mjs';

const baseline = process.argv.includes('--baseline');
const pins = ['apps/cad-studio/test/revolve-preview-axis-ownership-browser.mjs', 'apps/cad-studio/src/App.tsx',
  'apps/cad-studio/src/viewport/useViewportPicking.ts', 'apps/cad-studio/src/viewport/viewportPointerInput.ts',
  'packages/barocss-cad-model/src/app/profileCommands.ts',
  ...(baseline ? [] : ['apps/cad-studio/src/app/revolveAxisPick.ts'])];
const f = await createFlow({
  name: 'revolve-preview-axis-ownership', output: process.argv[2], envFrozen: 'D1162_SOURCE_FROZEN',
  initialFiles: pins, requiredFrozen: pins,
  qualification: 'Use original native edges through New and Join previews and refuse an edge generated by the preview.',
  limits: ['Desktop Chrome. Two upright stocks, one top sketch, two unchanged X-parallel source edges.'],
  inspectorSource: `
import { readFileSync } from 'node:fs';
import { toPartDocument } from '@barocss/cad-model/engine/part';
import { checkOutput, evaluateCadPart, faceGeometry, massPropertiesOf } from '@barocss/cad';
const doc = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const result = evaluateCadPart(toPartDocument(doc));
console.log(JSON.stringify(result.outputs.map(out => ({ id: out.id, valid: checkOutput(out).valid, count: out.bodyCount,
  mass: massPropertiesOf(out), cylinders: out.brep.faces.map(faceGeometry).filter(g => g.kind === 'cylinder') }))));
`,
});
const ref = node => ({ node, side: 'solid' });
const seed = {
  format: 'barocss-cad-model', schema: 3, units: 'mm', parameters: {}, nextId: 5,
  nodes: [
    { id: 'n0', kind: 'sketch', profile: 'rectangle', min: [0, 0], max: [40, 20] },
    { id: 'n1', kind: 'extrude', sketch: 0, height: 20 },
    { id: 'n2', kind: 'sketch', profile: 'rectangle', min: [50, 32], max: [90, 52] },
    { id: 'n3', kind: 'extrude', sketch: 2, height: 20 },
    { id: 'n4', kind: 'sketch', profile: 'rectangle', min: [10, 6], max: [20, 9], on: ref(1),
      plane: { origin: [0, 0, 20], normal: [0, 0, 1], xAxis: [1, 0, 0] } },
  ],
  outputs: { b1: ref(1), b3: ref(3) },
  bodies: { b1: { name: 'Axis stock' }, b3: { name: 'Decoy' } },
};
const button = (name, scope = f.page) => scope.getByRole('button', { name, exact: true });
const readEdge = async (world, key) => {
  const hit = await f.page.evaluate(([p, k]) => {
    const edge = window.__studioEdgeAt(p, 4);
    if (!edge || window.__studioSection().shownKeys[edge.body] !== k) return null;
    const pixel = window.__studioScreenOf(p);
    return document.elementFromPoint(...pixel)?.closest('.vp-canvas') ? { edge, pixel } : null;
  }, [world, key]);
  assert.ok(hit?.edge.segments.length, `Cannot find ${key} edge at ${world}`);
  return hit;
};
const topView = async () => {
  await button('Top', f.page.locator('.views')).click();
  await f.page.waitForFunction(() => document.querySelector('.view-cube .vc-label')?.textContent === 'TOP');
};
const waitKeys = keys => f.page.waitForFunction(keys => JSON.stringify(window.__studioSection().shownKeys) === JSON.stringify(keys), keys);
const horizontal = (hit, y, min, max) => {
  const points = hit.edge.segments.flatMap(segment => [segment.slice(0, 3), segment.slice(3)]);
  assert.ok(points.every(p => Math.abs(p[1] - y) < 1e-6 && Math.abs(p[2] - 20) < 1e-6), JSON.stringify(points));
  assert.deepEqual([Math.min(...points.map(p => p[0])), Math.max(...points.map(p => p[0]))], [min, max]);
};
const verifyAxis = (doc, y) => {
  const feature = doc.nodes[5];
  assert.equal(feature.kind, 'revolve');
  assert.equal(feature.angle, 360);
  assert.equal(feature.origin?.[1], y, JSON.stringify(feature));
  assert.ok(Math.abs(feature.dir?.[0]) === 1 && feature.dir[1] === 0, JSON.stringify(feature));
};

await f.run(async () => {
  await f.newPage();
  const [chooser] = await Promise.all([f.page.waitForEvent('filechooser'), button('Open').click()]);
  await chooser.setFiles({ name: 'D1162-revolve-axis.bcad', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(seed)) });
  await f.same(seed);
  await f.page.getByRole('group', { name: 'History', exact: true }).getByRole('button', { name: 'Sketch · rectangle', exact: true }).click();
  await f.editor().waitFor();
  await f.closeEditor();
  await f.page.evaluate(() => document.activeElement?.blur());
  await f.page.keyboard.press('Space');
  await f.page.locator('.palette input').fill('Revolve');
  await f.page.keyboard.press('Enter');
  const hud = f.page.getByRole('dialog', { name: 'Revolve', exact: true });
  await hud.waitFor();
  const status = value => hud.locator('.status').filter({ hasText: new RegExp('^' + value + '$') }).waitFor();
  const axisText = () => hud.locator('.hud-step').filter({ hasText: 'Axis' }).innerText();
  await status('preview');
  if (await button('Ortho').getAttribute('aria-pressed') !== 'true') await button('Ortho').click();
  await topView();
  await waitKeys(['b1', 'b3', 'b5']);
  f.phase = 'click the original Y0 edge during New body';
  const newA = await readEdge([30, 0, 20], 'b1');
  horizontal(newA, 0, 0, 40);
  await f.page.mouse.click(...newA.pixel);
  await hud.locator('.hud-step').filter({ hasText: /edge n1\./ }).waitFor();
  await status('preview');
  const axisA = await axisText();
  const apply = button('Apply', hud);
  if (!baseline) {
    await apply.click();
    await f.changed(seed);
    const newDoc = await f.doc(), native = await f.inspect('new-axis-a', newDoc);
    verifyAxis(newDoc, 0);
    assert.ok(native.every(body => body.valid && body.count === 1));
    const expected = 450 * Math.PI;
    assert.ok(Math.abs(native.find(body => body.id === 'n5').mass.volume - expected) < 1e-7);
    f.report.observations.push({ label: 'new', axis: newDoc.nodes[5], native });
    await f.undo();
    await f.same(seed);
    await f.page.getByRole('group', { name: 'History', exact: true }).getByRole('button', { name: 'Sketch · rectangle', exact: true }).click();
    await f.editor().waitFor();
    await f.closeEditor();
    await f.command('Revolve');
    await status('preview');
    await topView();
    await waitKeys(['b1', 'b3', 'b5']);
    await f.page.mouse.click(...(await readEdge([30, 0, 20], 'b1')).pixel);
    await hud.locator('.hud-step').filter({ hasText: /edge n1\./ }).waitFor();
    await status('preview');
  }
  await hud.getByLabel('Operation', { exact: true }).selectOption('join');
  await status('preview');
  await waitKeys(['b3', 'b6']);
  f.phase = 'read the original edges on the Join preview and click Y20';
  const joinedA = await readEdge([30, 0, 20], 'b6');
  horizontal(joinedA, 0, 0, 40);
  const joinedB = await readEdge([30, 20, 20], 'b6');
  horizontal(joinedB, 20, 0, 40);
  const generated = await readEdge([12, 9, 20], 'b6');
  horizontal(generated, 9, 10, 20);
  f.report.observations.push({ label: 'displayed-source-and-generated-edges', newA: newA.edge, joinedA: joinedA.edge, joinedB: joinedB.edge, generated: generated.edge });
  const prior = await axisText();
  assert.equal(prior, axisA);
  if (!baseline) {
    await f.page.mouse.click(...joinedA.pixel);
    await status('preview');
    await waitKeys(['b3', 'b6']);
    assert.equal(await axisText(), axisA);
    assert.ok(!(await f.toasts()).some(text => text.includes('Axis not selected')));
  }
  await f.page.mouse.click(...generated.pixel);
  if (!baseline) {
    await f.waitToast(/Axis not selected.*original straight edge/i);
    assert.equal(await axisText(), axisA);
    await f.same(seed);
    await f.snapshot('generated-edge-refused');
  }
  await f.page.mouse.click(...joinedB.pixel);
  if (baseline) {
    await f.page.waitForTimeout(500);
    const wrong = await axisText();
    f.report.observations.push({ label: 'original-y20', before: axisA, after: wrong });
    assert.ok(wrong === axisA || /n3\./.test(wrong), wrong);
    await f.snapshot('join-original-edge-wrong');
    assert.fail('Join read the drawn body ordinal as an unrelated accepted body');
  }
  await f.page.waitForFunction(axis => [...document.querySelectorAll('.hud .hud-step')].some(step => step.textContent.includes('Axis') && step.innerText !== axis && /edge n1\./.test(step.textContent)), axisA);
  await status('preview');
  await f.snapshot('join-axis-b-preview');
  await apply.click();
  await f.changed(seed);
  const accepted = await f.snapshot('join-axis-b');
  verifyAxis(accepted.doc, 20);
  assert.deepEqual(accepted.doc.nodes[6], { id: 'n6', kind: 'union', left: ref(1), right: ref(5) });
  const native = await f.inspect('join-axis-b-native', accepted.doc);
  assert.deepEqual(native.map(b => b.id), ['n3', 'n6']);
  assert.ok(native.every(body => body.valid && body.count === 1));
  assert.ok(Math.abs(native[0].mass.volume - 16000) < 1e-7);
  assert.ok(Math.abs(native[1].mass.volume - (16000 + 562.5 * Math.PI)) < 1e-6, JSON.stringify(native[1].mass));
  assert.ok([11, 14].every(radius => native[1].cylinders.some(c => Math.abs(c.r - radius) < 1e-7
    && Math.abs(Math.abs(c.a[0]) - 1) < 1e-7 && Math.abs(c.c[1] - 20) < 1e-7 && Math.abs(c.c[2] - 20) < 1e-7)));
  f.report.observations.push({ label: 'join', axis: accepted.doc.nodes[5], native });
  await f.undo();
  await f.same(seed);
  await f.redo();
  await f.same(accepted.doc);
  const saved = await f.save('revolve-join-axis');
  await f.freshOpen(saved.file, accepted.doc, 'reopened-join-axis');
  verifyAxis(await f.doc(), 20);
});
