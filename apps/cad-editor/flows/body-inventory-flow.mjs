import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

export async function runBodyInventoryFlow({page,cad,editor,result,evidence,prefix,resolve,repo}) {
  const fixture = resolve(repo,'apps/cad-editor/fixtures/complete-native-inventory.cad-document.json');
  const text = readFileSync(fixture,'utf8');
  const native = cad.parseCadDocument(text);
  assert.equal(native.document.assets.length,4); assert.equal(native.document.bodies.length,16);
  const requested = ['curve_body','foreign_line_0','foreign_surface_body','surface_body'];
  const ordered = ['surface_body','foreign_surface_body','foreign_line_0','curve_body'];
  assert.throws(()=>editor.createCadEditorSession(native.document),error=>error.context.field==='display-body-set');
  const pure = editor.createCadEditorSession(native.document,{displayBodyIds:requested});
  assert.deepEqual(pure.getSnapshot().displayBodyIds,ordered);
  assert.equal(pure.getSnapshot().bodyCapabilities.find(body=>body.bodyId==='foreign_surface_body').reason,'asset-has-siblings');
  pure.selectSurfacePole({bodyId:'surface_body',uIndex:1,vIndex:1});
  pure.stageSurfacePoleField('zMM','24');
  const beforePureDisplay=pure.getSnapshot(),pureDownload=pure.serializeAccepted();
  const displayCandidate=pure.prepareDisplayBodies(['surface_body']);
  displayCandidate.displayBodyIds[0]='foreign_surface_body';
  const afterPureDisplay=pure.acceptCandidate(displayCandidate.token);
  assert.deepEqual(afterPureDisplay.displayBodyIds,['surface_body']);
  assert.deepEqual(afterPureDisplay.pending,beforePureDisplay.pending);
  assert.deepEqual(afterPureDisplay.selection,beforePureDisplay.selection);
  assert.deepEqual(afterPureDisplay.accepted,beforePureDisplay.accepted);
  assert.deepEqual(afterPureDisplay.history,beforePureDisplay.history);
  pure.markDownloaded(pureDownload.token);
  pure.dispose();
  const snap = ()=>page.evaluate(()=>window.__cadEditorFlow.snapshot());
  const frame = ()=>page.evaluate(()=>window.__cadEditorFlow.display());
  const generation = (await snap()).generation;
  await page.getByLabel('Open native document file').setInputFiles(fixture);
  await page.getByTestId('open-display-choice').waitFor();
  assert.equal((await snap()).generation,generation);
  for(const id of requested) await page.getByTestId('open-body-'+id).check();
  await page.getByTestId('open-display-confirm').click();
  await page.waitForFunction(value=>window.__cadEditorFlow.snapshot().generation===value&&!window.__cadEditorFlow.snapshot().candidate,generation+1);
  const opened = await snap();
  assert.equal(opened.accepted.document.revision,7);
  assert.deepEqual(opened.accepted.document,native.document);
  assert.deepEqual(opened.displayBodyIds,ordered);
  assert.deepEqual((await frame()).state.documentBodies.map(body=>body.binding.bodyId),ordered);
  assert.equal((await frame()).state.surfaces.length,2); assert.equal((await frame()).state.curves.length,2);
  const unchanged = actual => {
    assert.deepEqual(actual.accepted.document.assets.slice(1),native.document.assets.slice(1));
    assert.deepEqual(actual.accepted.compiledAssets.slice(1),native.compiledAssets.slice(1));
    assert.deepEqual(actual.accepted.document.bodies,native.document.bodies);
  };
  const point = (actual,bodyId)=>cad.queryCadDocumentPoint(actual.accepted,cad.createCadGeometryReference(actual.accepted,{bodyId}).reference,bodyId.includes('surface')?{kind:'surface',u:0.5,v:0.5}:{kind:'curve',parameter:0.5}).pointMM;
  assert.deepEqual(point(opened,'foreign_surface_body'),[110,20,6]);
  assert.deepEqual(point(opened,'curve_body'),[-15,20,-5]);
  result.events.push({stage:'whole-native-inventory-open',assets:4,bodies:16,objects:opened.accepted.report.nativeObjectCount,requestedDisplayOrder:requested,actualCanonicalDisplayOrder:ordered,foreignSameGeometryIdPreserved:true,display:await frame()});

  await page.getByTestId('body-select-foreign_surface_body').click();
  await page.waitForFunction(()=>window.__cadEditorFlow.display().state.selectedGeometry?.modelId==='foreign_asset');
  assert.equal(await page.getByTestId('cad-editor-zMM').isDisabled(),true);
  const readonly = await page.evaluate(()=>{
    const s=window.__cadEditorFlow.session,before=s.getSnapshot();
    try{s.stageSurfacePoleField('zMM','99');return {code:'accepted'};}catch(error){return {code:error.code,context:error.context,before,after:s.getSnapshot()};}
  });
  assert.equal(readonly.code,'UNSUPPORTED'); assert.equal(readonly.context.field,'edit-capability'); assert.deepEqual(readonly.after,readonly.before);
  await page.getByTestId('fit-selected-body').click();
  const foreignFit = await frame();
  await page.getByTestId('body-select-surface_body').click();
  const bounds = await page.getByTestId('cad-editor-canvas').boundingBox();
  const beforeAmbiguous=await snap();
  await page.mouse.click(bounds.x+bounds.width/2,bounds.y+bounds.height/2);
  await page.waitForFunction(()=>window.__cadEditorFlow.error()?.message.includes('ambiguous'));
  assert.deepEqual((await snap()).accepted,beforeAmbiguous.accepted);
  assert.equal((await snap()).selectedBodyId,'surface_body');
  await page.getByTestId('body-select-surface_body').click();
  await page.mouse.click(bounds.x+bounds.width/2+13,bounds.y+bounds.height/2+7);
  await page.waitForFunction(()=>window.__cadEditorFlow.snapshot().selectedBodyId==='foreign_surface_body'&&window.__cadEditorFlow.display().state.selectedGeometry?.modelId==='foreign_asset');
  assert.equal((await snap()).selection.reference.assetId,'foreign_asset');
  await page.getByTestId('body-select-surface_body').click();
  await page.getByTestId('cad-editor-zMM').fill('24');
  const beforePick = await snap();
  await page.mouse.click(bounds.x+bounds.width/2+13,bounds.y+bounds.height/2+7);
  await page.getByTestId('cad-editor-transition').waitFor();
  assert.equal((await snap()).selectionTransition.target.bodyId,'foreign_surface_body');
  assert.equal((await snap()).selectedBodyId,'surface_body');
  await page.getByTestId('cad-editor-transition-cancel').click();
  assert.equal((await snap()).pending.zMM,'24'); assert.deepEqual((await snap()).accepted,beforePick.accepted);
  await page.getByTestId('cad-editor-discard').click();
  result.events.push({stage:'qualified-real-pointer-pick-and-fit',foreignRef:(await snap()).accepted.bodyBindings.find(body=>body.bodyId==='foreign_surface_body'),readonlySiblingAssetRefused:true,foreignFitCamera:foreignFit.state.camera,ambiguousPickRefusedWithoutNativeMutation:true,pickUsesAssetNamespace:true,draftPickCancelRetained:true});

  await page.getByTestId('cad-editor-zMM').fill('24');
  const beforeDisplay = await snap();
  const downloadCapture = await page.evaluate(()=>window.__cadEditorFlow.session.serializeAccepted());
  await page.getByTestId('body-visible-foreign_line_0').uncheck();
  await page.waitForFunction(value=>window.__cadEditorFlow.snapshot().displayGeneration===value&&!window.__cadEditorFlow.snapshot().candidate,beforeDisplay.displayGeneration+1);
  assert.equal((await frame()).state.documentBodies.length,3);
  await page.getByTestId('body-visible-foreign_line_0').check();
  await page.waitForFunction(value=>window.__cadEditorFlow.snapshot().displayGeneration===value&&!window.__cadEditorFlow.snapshot().candidate,beforeDisplay.displayGeneration+2);
  const revealed = await snap();
  assert.equal(revealed.pending.zMM,'24');
  assert.equal(revealed.generation,beforeDisplay.generation); assert.deepEqual(revealed.accepted,beforeDisplay.accepted); assert.deepEqual(revealed.history,beforeDisplay.history);
  assert.equal(cad.serializeCadDocument(revealed.accepted.document),downloadCapture.text);
  await page.evaluate(token=>window.__cadEditorFlow.session.markDownloaded(token),downloadCapture.token);
  const beforeBudget = await snap(),beforeBudgetFrame=await frame();
  await page.getByTestId('body-visible-hidden_line_0').click();
  await page.waitForFunction(()=>window.__cadEditorFlow.error()?.context.field==='display-body-set');
  await page.waitForFunction(read=>window.__cadEditorFlow.display().readIndex>read,beforeBudgetFrame.readIndex);
  assert.deepEqual((await snap()).accepted,beforeBudget.accepted); assert.deepEqual((await snap()).history,beforeBudget.history);
  assert.deepEqual((await snap()).displayBodyIds,beforeBudget.displayBodyIds); assert.equal((await frame()).pixelHash,beforeBudgetFrame.pixelHash);
  assert.equal(await page.getByTestId('body-visible-hidden_line_0').isChecked(),false);
  await page.getByTestId('body-visible-foreign_line_0').uncheck();
  await page.waitForFunction(value=>window.__cadEditorFlow.snapshot().displayGeneration===value&&!window.__cadEditorFlow.snapshot().candidate,revealed.displayGeneration+1);
  const beforeUnsupported=await snap(),beforeUnsupportedFrame=await frame();
  await page.getByTestId('body-visible-hidden_line_0').click();
  await page.waitForFunction(()=>window.__cadEditorFlow.error()?.code==='DISPLAY');
  await page.waitForFunction(read=>window.__cadEditorFlow.display().readIndex>read,beforeUnsupportedFrame.readIndex);
  const refused=await snap(),refusedFrame=await frame();
  assert.deepEqual(refused.accepted,beforeUnsupported.accepted);assert.deepEqual(refused.history,beforeUnsupported.history);
  assert.deepEqual(refused.displayBodyIds,beforeUnsupported.displayBodyIds);assert.equal(refused.displayGeneration,beforeUnsupported.displayGeneration);
  assert.equal(refusedFrame.pixelHash,beforeUnsupportedFrame.pixelHash);assert.deepEqual(refusedFrame.state.camera,beforeUnsupportedFrame.state.camera);
  assert.equal(refusedFrame.width,beforeUnsupportedFrame.width);assert.equal(refusedFrame.height,beforeUnsupportedFrame.height);
  assert.equal(await page.getByTestId('body-visible-hidden_line_0').isChecked(),false);
  result.events.push({stage:'bounded-display-hide-reveal-refusals',hideRevealNativeHistoryBytesUnchanged:true,displayDoesNotInvalidateDownloadCapture:true,overBudgetFiveNotTruncated:true,actualUnsupportedDegreeFiveSiblingRefused:true,diagnostic:await page.evaluate(()=>window.__cadEditorFlow.error()),retainedFreshFrame:{hash:refusedFrame.pixelHash,readIndex:refusedFrame.readIndex}});

  await page.getByTestId('cad-editor-discard').click();
  await page.getByTestId('body-select-hidden_line_0').click();
  await page.waitForFunction(()=>window.__cadEditorFlow.snapshot().selectedBodyId==='hidden_line_0'&&window.__cadEditorFlow.display().state.selectedGeometry===null);
  const hiddenSelected=await snap(),beforeHiddenFit=await frame();
  await page.getByTestId('fit-selected-body').click();
  await page.waitForFunction(()=>window.__cadEditorFlow.error()?.context.field==='fit-selection');
  await page.waitForFunction(read=>window.__cadEditorFlow.display().readIndex>read,beforeHiddenFit.readIndex);
  assert.deepEqual((await snap()).accepted,hiddenSelected.accepted); assert.deepEqual((await snap()).history,hiddenSelected.history);
  assert.equal((await snap()).selectedBodyId,'hidden_line_0'); assert.equal((await frame()).pixelHash,beforeHiddenFit.pixelHash);
  assert.deepEqual((await frame()).state.camera,beforeHiddenFit.state.camera);
  result.events.push({stage:'hidden-native-selection-fit-refusal',nativeSelectionRetainedWithoutDisplayBinding:true,fitRefusedWithoutFrameOrSourceChange:true});
  await page.getByTestId('body-select-surface_body').click();
  await page.getByTestId('cad-editor-zMM').fill('24');await page.getByTestId('cad-editor-weight').fill('2');
  const beforeApply=await snap(),beforeApplyFrame=await frame();
  await page.getByTestId('cad-editor-apply').click();
  await page.waitForFunction(value=>window.__cadEditorFlow.snapshot().generation===value&&!window.__cadEditorFlow.snapshot().candidate,beforeApply.generation+1);
  const edited=await snap();unchanged(edited);
  assert.equal(edited.accepted.document.revision,8);assert.equal(edited.accepted.document.assets[0].revision,3);
  assert.ok(Math.abs(point(edited,'surface_body')[2]-56/5)<1e-8);assert.deepEqual(point(edited,'foreign_surface_body'),[110,20,6]);
  assert.notEqual((await frame()).pixelHash,beforeApplyFrame.pixelHash);
  await page.screenshot({path:resolve(evidence,prefix+'-complete-inventory.png')});
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Download',exact:true}).click();
  const download=await downloadPromise,path=resolve(evidence,prefix+'-inventory-'+download.suggestedFilename());await download.saveAs(path);
  const bytes=readFileSync(path,'utf8');assert.equal(bytes,cad.serializeCadDocument(edited.accepted.document));
  const cold=cad.parseCadDocument(bytes);unchanged({accepted:cold});assert.equal(cold.document.bodies.length,16);
  assert.equal(JSON.parse(bytes).displayBodyIds,undefined);
  const freshContext=await page.context().browser().newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
  try{
    const fresh=await freshContext.newPage();fresh.on('pageerror',error=>result.pageErrors.push(error.message));
    await fresh.goto(page.url());await fresh.locator('[data-viewer-ready="true"]').waitFor();
    await fresh.getByLabel('Open native document file').setInputFiles(path);
    await fresh.getByTestId('open-display-choice').waitFor();
    for(const id of ['surface_body','curve_body'])await fresh.getByTestId('open-body-'+id).check();
    await fresh.getByTestId('open-display-confirm').click();
    await fresh.waitForFunction(()=>window.__cadEditorFlow.snapshot().generation===1&&!window.__cadEditorFlow.snapshot().candidate);
    await fresh.getByTestId('body-select-surface_body').click();await fresh.getByTestId('cad-editor-zMM').fill('28');await fresh.getByTestId('cad-editor-zMM').press('Enter');
    await fresh.waitForFunction(()=>window.__cadEditorFlow.snapshot().generation===2&&!window.__cadEditorFlow.snapshot().candidate);
    const actual=await fresh.evaluate(()=>window.__cadEditorFlow.snapshot());unchanged(actual);
    assert.equal(actual.accepted.document.revision,9);assert.equal(actual.accepted.document.assets[0].revision,4);
    assert.ok(Math.abs(point(actual,'surface_body')[2]-64/5)<1e-8);
    assert.deepEqual(point(actual,'foreign_surface_body'),[110,20,6]);
    result.events.push({stage:'complete-inventory-native-file-roundtrip',path,nativeEditedPoint:point(edited,'surface_body'),foreignSameIdPoint:point(actual,'foreign_surface_body'),freshEnterReeditPoint:point(actual,'surface_body'),completeHiddenSourceModelsBodiesRevisionsPreserved:true,actualDisplayedBodies:(await fresh.evaluate(()=>window.__cadEditorFlow.display())).state.documentBodies.length});
  }finally{await freshContext.close();}
}
