import {build} from 'esbuild';
import {readFileSync,realpathSync,appendFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const require=createRequire(import.meta.url),root=fileURLToPath(new URL('../',import.meta.url));
const repo=realpathSync(resolve(root,'../..'));
function outsideWorktree(path){const value=resolve(path);if(value===repo||value.startsWith(`${repo}/`))throw new Error('Test source overlays and receipts must stay outside the worktree');return value;}
function sourceOverlay(){
  const manifest=process.env.BAROCSS_CAD_REACT_TEST_SOURCE_OVERLAY;
  if(!manifest)return null;
  const input=JSON.parse(readFileSync(outsideWorktree(realpathSync(manifest)),'utf8'));
  const source=realpathSync(input.source),file=outsideWorktree(realpathSync(input.file));
  const allowed=['src/model-host.ts','src/viewer.ts'].map(path=>realpathSync(resolve(root,path)));
  if(!allowed.includes(source))throw new Error('Only ModelHost or ExistingViewerHost source can be overlaid');
  const trace=process.env.BAROCSS_CAD_REACT_TEST_SOURCE_OVERLAY_TRACE;
  return{source,file,contents:readFileSync(file,'utf8'),trace:trace?outsideWorktree(resolve(realpathSync(resolve(trace,'..')),trace.split('/').at(-1))):null};
}
/** Build only on an explicit test run; generated bytes stay outside the repository. */
export async function loadSource(t,entry,{stubViewer=false}={}) {
  const temp=await mkdtemp(join(tmpdir(),'barocss-cad-react-test-'));
  t.after(()=>rm(temp,{recursive:true,force:true}));
  const out=join(temp,'entry.mjs'),overlay=sourceOverlay();
  await build({entryPoints:[resolve(root,entry)],outfile:out,bundle:true,format:'esm',platform:'node',target:'es2022',logLevel:'silent',plugins:[{
    name:'existing-react-singleton',setup(build){
      if(overlay)build.onLoad({filter:/[\\/](?:model-host|viewer)\.ts$/},args=>{
        if(realpathSync(args.path)!==overlay.source)return;
        if(overlay.trace)appendFileSync(overlay.trace,JSON.stringify({source:overlay.source,file:overlay.file})+'\n');
        return{contents:overlay.contents,loader:'ts',resolveDir:resolve(overlay.source,'..')};
      });
      build.onResolve({filter:/^@barocss\/cad-model\/(.+)$/},args=>({path:resolve(root,'../barocss-cad-model/src',args.path.slice('@barocss/cad-model/'.length)+'.ts')}));
      build.onResolve({filter:/^react(?:\/.*)?$/},args=>({path:require.resolve(args.path),external:true}));
      if(stubViewer)build.onResolve({filter:/^@barocss\/viewer$/},()=>({path:'viewer-factory',namespace:'test'}));
      if(stubViewer)build.onLoad({filter:/.*/,namespace:'test'},()=>({contents:'export function createViewer(){throw new Error("No GPU calls in this controlled sink test");}',loader:'js'}));
    }
  }]});
  return import(pathToFileURL(out).href);
}
